//! The printer: one pass into one buffer, already in the form it is kept in, with no formatter
//! after it. A reference to a named type prints its name; anything else prints inline, at most
//! `flowapi::names::MAX_INLINE` shapes deep (the names pass saw to it).

use crate::object::object;
use flowapi::Program;
use flowapi::graph::{Array, Branches, Kind, Type};
use flowapi::id::TypeId;

/// How tightly an expression binds, to know where it needs parentheses.
#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub(crate) enum Prec {
    Union,
    Intersection,
    Primary,
}

const HEADER: &str =
    "// Generated by flowapi from an API description. Do not edit: generate again.\n";

pub(crate) fn program(p: &Program<'_>) -> String {
    let mut out = String::with_capacity(4096 + p.decls().len() * 128);
    out.push_str(HEADER);
    for decl in p.decls() {
        out.push('\n');
        doc(&mut out, p.get(decl.ty));
        out.push_str("export type ");
        out.push_str(&decl.name);
        out.push_str(" = ");
        body(&mut out, p, decl.ty, Prec::Union);
        out.push_str(";\n");
    }
    out
}

fn doc(out: &mut String, ty: &Type<'_>) {
    let mut lines: Vec<String> = Vec::new();
    for text in [&ty.title, &ty.description].into_iter().flatten() {
        lines.extend(text.lines().map(|l| l.replace("*/", "*\\/")));
    }
    if ty.deprecated {
        lines.push(String::from("@deprecated"));
    }
    let lossy: Vec<&str> = ty.lossy.iter().map(|k| k.name()).collect();
    if !lossy.is_empty() {
        lines.push(format!("Not checked by this type: {}.", lossy.join(", ")));
    }
    if lines.is_empty() {
        return;
    }
    out.push_str("/**\n");
    for line in lines {
        out.push_str(" *");
        if !line.is_empty() {
            out.push(' ');
            out.push_str(line.trim_end());
        }
        out.push('\n');
    }
    out.push_str(" */\n");
}

/// A reference: the name of a named type, the shape of any other.
pub(crate) fn reference(out: &mut String, p: &Program<'_>, id: TypeId, ctx: Prec) {
    let id = p.resolve(id);
    match p.name_of(id) {
        Some(name) => out.push_str(name),
        None => body(out, p, id, ctx),
    }
}

/// A type's own expression.
fn body(out: &mut String, p: &Program<'_>, id: TypeId, ctx: Prec) {
    match &p.get(id).kind {
        Kind::Any => out.push_str("unknown"),
        Kind::Never => out.push_str("never"),
        Kind::Alias(t) => reference(out, p, *t, ctx),
        // A member the lowering widened to any value (a broken cycle) makes the union any value;
        // one that allows none makes the intersection none.
        Kind::Union(ms) if ms.iter().any(|&m| p.is_any(m)) => out.push_str("unknown"),
        Kind::Intersection(ms) if ms.iter().any(|&m| p.is_never(m)) => out.push_str("never"),
        Kind::Union(ms) if ms.len() > 1 && ms.iter().all(|&m| shape(p, m).is_some()) => {
            // A union of unnamed shapes is the union of their members, each once.
            let mut parts: Vec<String> = Vec::new();
            for b in ms.iter().filter_map(|&m| shape(p, m)) {
                for part in value_parts(p, b) {
                    if !parts.contains(&part) {
                        parts.push(part);
                    }
                }
            }
            let paren = ctx > Prec::Union && parts.len() > 1;
            if paren {
                out.push('(');
            }
            out.push_str(if parts.is_empty() { "never" } else { "" });
            out.push_str(&parts.join(" | "));
            if paren {
                out.push(')');
            }
        }
        Kind::Union(ms) if ms.iter().any(|&m| p.is_never(m)) => {
            // A member that allows no value adds nothing to a union.
            let kept: Vec<TypeId> = ms.iter().copied().filter(|&m| !p.is_never(m)).collect();
            match kept.as_slice() {
                [] => out.push_str("never"),
                _ => list(out, p, &kept, " | ", Prec::Union, ctx),
            }
        }
        Kind::Union(ms) => list(out, p, ms, " | ", Prec::Union, ctx),
        Kind::Intersection(ms) => list(out, p, ms, " & ", Prec::Intersection, ctx),
        Kind::Value(b) => value(out, p, b, ctx),
    }
}

/// The shape a reference prints inline, when it is one.
fn shape<'p, 't>(p: &'p Program<'t>, id: TypeId) -> Option<&'p Branches<'t>> {
    let id = p.resolve(id);
    if p.name_of(id).is_some() {
        return None;
    }
    match &p.get(id).kind {
        Kind::Value(b) => Some(b),
        Kind::Any | Kind::Never | Kind::Alias(_) | Kind::Union(_) | Kind::Intersection(_) => None,
    }
}

fn list(out: &mut String, p: &Program<'_>, ms: &[TypeId], sep: &str, own: Prec, ctx: Prec) {
    let paren = own < ctx && ms.len() > 1;
    if paren {
        out.push('(');
    }
    for (i, &m) in ms.iter().enumerate() {
        if i > 0 {
            out.push_str(sep);
        }
        // `|` inside `|` needs no parentheses; anything looser than `&` inside `&` does.
        let inner = match own {
            Prec::Union => Prec::Union,
            Prec::Intersection | Prec::Primary => next(own),
        };
        reference(out, p, m, if ms.len() > 1 { inner } else { ctx });
    }
    if paren {
        out.push(')');
    }
}

fn next(prec: Prec) -> Prec {
    match prec {
        Prec::Union => Prec::Intersection,
        Prec::Intersection | Prec::Primary => Prec::Primary,
    }
}

fn value(out: &mut String, p: &Program<'_>, b: &Branches<'_>, ctx: Prec) {
    let parts = value_parts(p, b);
    match parts.len() {
        0 => out.push_str("never"),
        1 => out.push_str(parts.first().map_or("never", String::as_str)),
        _ => {
            let paren = ctx > Prec::Union && parts_count(b) > 1;
            if paren {
                out.push('(');
            }
            out.push_str(&parts.join(" | "));
            if paren {
                out.push(')');
            }
        }
    }
}

/// A shape's members, one per kind or literal.
fn value_parts(p: &Program<'_>, b: &Branches<'_>) -> Vec<String> {
    let mut parts: Vec<String> = Vec::new();
    if let Some(o) = &b.object {
        let mut s = String::new();
        object(&mut s, p, o);
        parts.push(s);
    }
    if let Some(a) = &b.array {
        let mut s = String::new();
        array(&mut s, p, a);
        parts.push(s);
    }
    if let Some(s) = &b.string {
        match &s.lits {
            Some(lits) => parts.extend(lits.iter().map(|l| l.raw.to_owned())),
            None => parts.push(String::from("string")),
        }
    }
    if let Some(n) = &b.number {
        match &n.lits {
            Some(lits) => parts.extend(lits.iter().map(|l| l.raw.to_owned())),
            None => parts.push(String::from("number")),
        }
    }
    match (b.boolean.allow_true, b.boolean.allow_false) {
        (true, true) => parts.push(String::from("boolean")),
        (true, false) => parts.push(String::from("true")),
        (false, true) => parts.push(String::from("false")),
        (false, false) => {}
    }
    if b.null {
        parts.push(String::from("null"));
    }
    parts
}

fn parts_count(b: &Branches<'_>) -> usize {
    let lits = |n: Option<usize>| n.unwrap_or(1);
    usize::from(b.object.is_some())
        + usize::from(b.array.is_some())
        + b.string
            .as_ref()
            .map_or(0, |s| lits(s.lits.as_ref().map(Vec::len)))
        + b.number
            .as_ref()
            .map_or(0, |n| lits(n.lits.as_ref().map(Vec::len)))
        + usize::from(b.boolean.allow_true || b.boolean.allow_false)
        + usize::from(b.null)
}

fn array(out: &mut String, p: &Program<'_>, a: &Array) {
    if a.prefix.is_empty() && !p.is_never(a.rest) {
        let mut item = String::new();
        reference(&mut item, p, a.rest, Prec::Primary);
        out.push_str(&item);
        out.push_str("[]");
        return;
    }
    out.push('[');
    for (i, &t) in a.prefix.iter().enumerate() {
        if i > 0 {
            out.push_str(", ");
        }
        // `T?` binds tighter than a union: an optional element that is one is parenthesized.
        let optional = i >= a.min;
        reference(
            out,
            p,
            t,
            if optional { Prec::Primary } else { Prec::Union },
        );
        if optional {
            out.push('?');
        }
    }
    if !p.is_never(a.rest) {
        if !a.prefix.is_empty() {
            out.push_str(", ");
        }
        out.push_str("...");
        reference(out, p, a.rest, Prec::Primary);
        out.push_str("[]");
    }
    out.push(']');
}
