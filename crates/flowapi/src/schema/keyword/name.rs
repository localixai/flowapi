//! Each keyword's name, as a diagnostic or a comment writes it.

use super::Keyword;

impl Keyword {
    /// The keyword as written (`$defs` for both of its spellings, `$id` for draft 4's `id` too).
    #[must_use]
    pub fn name(self) -> &'static str {
        match self {
            Self::Schema => "$schema",
            Self::Ref => "$ref",
            Self::Anchor => "$anchor",
            Self::DynamicRef => "$dynamicRef",
            Self::DynamicAnchor => "$dynamicAnchor",
            Self::RecursiveRef => "$recursiveRef",
            Self::RecursiveAnchor => "$recursiveAnchor",
            Self::Vocabulary => "$vocabulary",
            Self::Comment => "$comment",
            Self::Defs => "$defs",
            Self::AllOf => "allOf",
            Self::AnyOf => "anyOf",
            Self::OneOf => "oneOf",
            Self::Not => "not",
            Self::If => "if",
            Self::Then => "then",
            Self::Else => "else",
            Self::DependentSchemas => "dependentSchemas",
            Self::Dependencies => "dependencies",
            Self::PrefixItems => "prefixItems",
            Self::Items => "items",
            Self::AdditionalItems => "additionalItems",
            Self::Contains => "contains",
            Self::Properties => "properties",
            Self::PatternProperties => "patternProperties",
            Self::AdditionalProperties => "additionalProperties",
            Self::PropertyNames => "propertyNames",
            Self::UnevaluatedItems => "unevaluatedItems",
            Self::UnevaluatedProperties => "unevaluatedProperties",
            Self::Type => "type",
            Self::Enum => "enum",
            Self::Const => "const",
            Self::MultipleOf => "multipleOf",
            Self::Maximum => "maximum",
            Self::ExclusiveMaximum => "exclusiveMaximum",
            Self::Minimum => "minimum",
            Self::ExclusiveMinimum => "exclusiveMinimum",
            Self::MaxLength => "maxLength",
            Self::MinLength => "minLength",
            Self::Pattern => "pattern",
            Self::MaxItems => "maxItems",
            Self::MinItems => "minItems",
            Self::UniqueItems => "uniqueItems",
            Self::MaxContains => "maxContains",
            Self::MinContains => "minContains",
            Self::MaxProperties => "maxProperties",
            Self::MinProperties => "minProperties",
            Self::Required => "required",
            Self::DependentRequired => "dependentRequired",
            Self::Format => "format",
            Self::ContentEncoding => "contentEncoding",
            Self::ContentMediaType => "contentMediaType",
            Self::ContentSchema => "contentSchema",
            Self::Title => "title",
            Self::Description => "description",
            Self::Default => "default",
            Self::Deprecated => "deprecated",
            Self::ReadOnly => "readOnly",
            Self::WriteOnly => "writeOnly",
            Self::Examples => "examples",
            Self::Discriminator => "discriminator",
            Self::Xml => "xml",
            Self::ExternalDocs => "externalDocs",
            Self::Example => "example",
            Self::Id => "$id",
            Self::Nullable => "nullable",
            Self::Extension => "x-…",
            Self::Unknown => "an unknown keyword",
        }
    }
}
