//! `src/client.ts`, the client class the config names (`package.client`), and `src/index.ts`,
//! the package's entry. The client's settings are what the config decides: its environments and
//! the variable over them, each security scheme's option and variable, the timeout, retries and
//! longest retry wait (milliseconds here, seconds in the config); the description's servers and
//! schemes come from the operations table. A credential's option is its scheme's name in camel
//! case (`api_key` is `apiKey`), which `config check` holds apart from the client's own options.

use super::camel;
use super::resources::{class_of, member_of, path_of};
use crate::config::model::Config;
use crate::model::{Auth, Service};
use crate::words::{self, pascal};
use flowapi_ts::string_literal as lit;
use std::fmt::Write as _;

/// Seconds as whole milliseconds, `default` seconds when the config gives none.
fn ms(seconds: Option<f64>, default: f64) -> String {
    format!("{}", (seconds.unwrap_or(default) * 1000.0).round())
}

/// The client's name, and the name of its options' type.
fn names(c: &Config) -> (String, String) {
    let client = c
        .client
        .as_ref()
        .map_or_else(|| String::from("Client"), |n| n.name.clone());
    let options = format!("{}Options", pascal(&words::words(&client)));
    (client, options)
}

/// The environment variable the client reads its log level from: `SHOP_LOG` for `Shop`.
pub(crate) fn log_env(client: &str) -> String {
    format!("{}_LOG", words::upper(&words::words(client)))
}

/// `src/client.ts`.
pub(crate) fn client(c: &Config, service: &Service) -> String {
    let (client, options) = names(c);
    let s = &c.settings;
    let mut out = String::from(
        "// Generated by flowapi from flowapi-sdk.yml and the API description. Do not edit: generate again.\n\n",
    );
    out.push_str(
        "import * as $api from \"./api.js\";\nimport * as $core from \"./core/index.js\";\n",
    );
    let top: Vec<usize> = (0..c.resources.len())
        .filter(|&i| c.resources.get(i).is_some_and(|r| r.parent.is_none()))
        .collect();
    for &i in &top {
        let class = class_of(c, i);
        let _ = writeln!(
            out,
            "import {{ {class} as ${class} }} from \"./{}.js\";",
            path_of(c, i)
        );
    }
    let envs: Vec<String> = s
        .urls
        .iter()
        .map(|(n, u)| format!("{}: {}", lit(n), lit(u)))
        .collect();
    out.push_str(
        "\n/** What the config decides of the client. */\nconst $settings: $core.Settings = {\n",
    );
    let _ = writeln!(out, "  client: {},", lit(&client));
    let _ = writeln!(out, "  environments: {{ {} }},", envs.join(", "));
    let default = c.default_environment.as_ref().and_then(|d| {
        s.urls
            .iter()
            .find(|(n, _)| words::same(n, &d.name))
            .map(|(n, _)| n)
    });
    if let Some(d) = default {
        let _ = writeln!(out, "  defaultEnvironment: {},", lit(d));
    }
    if let Some(v) = &s.base_url_env {
        let _ = writeln!(out, "  baseURLEnv: {},", lit(v));
    }
    let _ = writeln!(out, "  logEnv: {},", lit(&log_env(&client)));
    let auth: Vec<String> = c
        .auth
        .iter()
        .map(|a| {
            let option = camel(&words::words(&a.name));
            let env = s
                .auth_env
                .iter()
                .find(|(n, _)| *n == a.name)
                .map(|(_, v)| format!(", env: {}", lit(v)));
            format!(
                "{}: {{ option: {}{} }}",
                lit(&a.name),
                lit(&option),
                env.unwrap_or_default()
            )
        })
        .collect();
    let _ = writeln!(out, "  auth: {{ {} }},", auth.join(", "));
    let _ = writeln!(out, "  timeout: {},", ms(s.timeout, 60.0));
    let _ = writeln!(out, "  maxRetries: {},", s.retries.unwrap_or(2));
    let _ = writeln!(out, "  maxRetryDelay: {},", ms(s.max_retry_delay, 60.0));
    out.push_str("  servers: $api.flowapiServers,\n  schemes: $api.flowapiSecuritySchemes,\n  readsBytes: $api.flowapiReadsBytes,\n};\n");
    options_type(c, service, &client, &options, &mut out);
    class(c, &client, &options, &top, &mut out);
    out
}

/// The type of the client's options: the runtime's, and a credential for each scheme.
fn options_type(c: &Config, service: &Service, client: &str, options: &str, out: &mut String) {
    let s = &c.settings;
    let env_type: Vec<String> = s.urls.iter().map(|(n, _)| lit(n)).collect();
    let env_type = if env_type.is_empty() {
        String::from("never")
    } else {
        env_type.join(" | ")
    };
    let _ = writeln!(
        out,
        "\n/** The options of a `{client}`: the runtime's, and a credential for each security scheme it sends. */"
    );
    let _ = writeln!(
        out,
        "export type {options} = $core.ClientOptions<{env_type}> & {{"
    );
    for a in &c.auth {
        let scheme = service.schemes.iter().find(|x| x.name == a.name);
        let basic = scheme
            .is_some_and(|x| matches!(&x.auth, Auth::Http { scheme, .. } if scheme == "basic"));
        let env = s
            .auth_env
            .iter()
            .find(|(n, _)| *n == a.name)
            .map(|(_, v)| format!(", else `{v}`"))
            .unwrap_or_default();
        let _ = writeln!(
            out,
            "  /** The credential of the security scheme `{}`{env}; `null` reads no variable. */",
            super::doc(&a.name)
        );
        let kind = if basic {
            "BasicCredential"
        } else {
            "Credential"
        };
        let option = camel(&words::words(&a.name));
        let key = if option.starts_with(|c: char| c.is_ascii_alphabetic()) {
            option
        } else {
            lit(&option)
        };
        let _ = writeln!(out, "  {key}?: $core.{kind} | null | undefined;");
    }
    out.push_str("};\n");
}

/// The client class.
fn class(c: &Config, client: &str, options: &str, top: &[usize], out: &mut String) {
    let example = top
        .first()
        .map(|&i| format!(" (`client.{}`)", member_of(c, i)))
        .unwrap_or_default();
    let _ = writeln!(
        out,
        "\n/** The API's client: a member for each resource{example}, and `request` for a call no\n * operation describes. */"
    );
    let _ = writeln!(out, "export class {client} {{");
    out.push_str("  readonly #core: $core.Core;\n");
    let _ = writeln!(out, "  readonly #options: {options};");
    for &i in top {
        let _ = writeln!(out, "  readonly {}: ${};", member_of(c, i), class_of(c, i));
    }
    let _ = writeln!(out, "\n  constructor(options: {options} = {{}}) {{");
    out.push_str("    this.#options = { ...options };\n    this.#core = new $core.Core($settings, options);\n");
    for &i in top {
        let _ = writeln!(
            out,
            "    this.{} = new ${}(this.#core);",
            member_of(c, i),
            class_of(c, i)
        );
    }
    out.push_str("  }\n");
    out.push_str(concat!(
        "\n  /** The base URL calls go to, unless an operation has servers of its own. */\n",
        "  get baseURL(): string | null {\n    return this.#core.baseURL;\n  }\n",
        "\n  /** Milliseconds an attempt may take, its body read; `null` for no limit. */\n",
        "  get timeout(): number | null {\n    return this.#core.timeout;\n  }\n",
        "\n  /** How many times a failed attempt is tried again. */\n",
        "  get maxRetries(): number {\n    return this.#core.maxRetries;\n  }\n",
        "\n  /** A client of the same class with these options over this one's: one given as `undefined`\n",
        "   * keeps this one's. */\n",
    ));
    let _ = writeln!(out, "  withOptions(options: {options}): this {{");
    out.push_str("    const next: Record<string, unknown> = { ...this.#options };\n");
    out.push_str("    for (const [key, value] of Object.entries(options)) if (value !== undefined) next[key] = value;\n");
    let _ = writeln!(
        out,
        "    return new (this.constructor as new (options: {options}) => this)(next as {options});"
    );
    out.push_str(concat!(
        "  }\n",
        "\n  /** A call by method and path that no operation describes, with every credential the\n",
        "   * client has. */\n",
        "  request<T = unknown>(method: string, path: string, options?: $core.RawRequest): $core.ApiCall<T> {\n",
        "    return $core.request<T>(this.#core, method, path, options);\n  }\n}\n",
    ));
}

/// `src/index.ts`: the client, its options, the runtime's errors and types (those `api.md` writes
/// a method's signature with among them: `Input`, `Data`, `ItemOf`), and the API module.
pub(crate) fn index(c: &Config) -> String {
    let (client, options) = names(c);
    let mut out = String::from(
        "// Generated by flowapi from flowapi-sdk.yml and the API description. Do not edit: generate again.\n\n",
    );
    let _ = writeln!(
        out,
        "export {{ {client}, {client} as default, type {options} }} from \"./client.js\";"
    );
    out.push_str(concat!(
        "export {\n  APIConnectionError,\n  APIConnectionTimeoutError,\n  APIError,\n  APIUserAbortError,\n",
        "  ApiCall,\n  AuthenticationError,\n  BadRequestError,\n  type BasicCredential,\n  ConflictError,\n",
        "  type Credential,\n  CrossOriginRedirectError,\n  type Data,\n  type Fetch,\n  type FetchResponse,\n",
        "  type HeadersInput,\n  type Input,\n  InternalServerError,\n  type ItemOf,\n  type LogLevel,\n",
        "  type Logger,\n  NotFoundError,\n  type Outcome,\n  Page,\n  PagePromise,\n  PermissionDeniedError,\n",
        "  type QueryInput,\n  RateLimitError,\n  type RawRequest,\n  type RequestOptions,\n  RequestTimeoutError,\n  SdkError,\n  type ServerSentEvent,\n  Stream,\n",
        "  UnprocessableEntityError,\n} from \"./core/index.js\";\nexport * from \"./api.js\";\n",
    ));
    out
}
