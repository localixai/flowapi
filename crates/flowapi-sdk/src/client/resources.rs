//! A class per resource of the config's tree, in `src/resources/` (a resource under another in
//! the folder named after it), each method calling its operation through the runtime: `call` for
//! its data, `page` for a list the config pages (its scheme printed as the runtime reads it, each
//! parameter with where it goes), `stream` for a streamed one. Names are the config's words:
//! methods and members in camel case, classes in Pascal case, files in kebab case. A class
//! imports another under a `$` name, which no word can make, so no name of the config shadows one.

use super::{camel, doc};
use crate::config::check::{effective, find};
use crate::config::issue::Issues;
use crate::config::model::{Config, Method};
use crate::ops::Ops;
use crate::paging::Paging;
use crate::words::{self, pascal};
use flowapi::spec::{Location, Operation};
use flowapi::{File, Program};
use flowapi_ts::string_literal as lit;
use std::fmt::Write as _;

/// What the resources are printed from.
pub(crate) struct Context<'a> {
    pub(crate) config: &'a Config,
    pub(crate) program: &'a Program<'a>,
    pub(crate) ops: &'a Ops<'a, 'a>,
    /// Each method's operation, by index into `ops.list`.
    pub(crate) resolved: &'a [Option<usize>],
    /// Each method's endpoint, by index into the program's endpoints.
    pub(crate) endpoints: &'a [Option<usize>],
    /// Each endpoint's function name before `Request` and `Response`.
    pub(crate) bases: Vec<Option<String>>,
}

/// A resource's names from the top, as words each.
fn trail(c: &Config, resource: usize) -> Vec<Vec<String>> {
    let path = c.path(resource);
    path.split('.').map(words::words).collect()
}

/// A resource's file, from `src/`: `resources/pets/photos.ts`.
pub(crate) fn path_of(c: &Config, resource: usize) -> String {
    let names: Vec<String> = trail(c, resource)
        .iter()
        .map(|w| words::join(w, "-"))
        .collect();
    format!("resources/{}", names.join("/"))
}

/// A resource's class.
pub(crate) fn class_of(c: &Config, resource: usize) -> String {
    c.resources
        .get(resource)
        .map(|r| pascal(&words::words(&r.name.name)))
        .unwrap_or_default()
}

/// The member a resource is on its parent: its name in camel case.
pub(crate) fn member_of(c: &Config, resource: usize) -> String {
    c.resources
        .get(resource)
        .map(|r| camel(&words::words(&r.name.name)))
        .unwrap_or_default()
}

/// Every resource's file.
pub(crate) fn files(ctx: &Context<'_>, issues: &mut Issues) -> Vec<File> {
    let c = ctx.config;
    let mut out = Vec::new();
    for (i, _) in c.resources.iter().enumerate() {
        let depth = trail(c, i).len();
        let up = "../".repeat(depth);
        let own = path_of(c, i);
        let mut text = String::from(
            "// Generated by flowapi from sdk-anything.yml and the API description. Do not edit: generate again.\n\n",
        );
        let _ = writeln!(text, "import * as $api from \"{up}api.js\";");
        let _ = writeln!(text, "import * as $core from \"{up}core/index.js\";");
        let children: Vec<usize> = (0..c.resources.len())
            .filter(|&j| c.resources.get(j).is_some_and(|r| r.parent == Some(i)))
            .collect();
        let leaf = own.rsplit('/').next().unwrap_or("");
        for &j in &children {
            let child = path_of(c, j);
            let file = child.rsplit('/').next().unwrap_or("");
            let class = class_of(c, j);
            let _ = writeln!(
                text,
                "import {{ {class} as ${class} }} from \"./{leaf}/{file}.js\";"
            );
        }
        let _ = writeln!(text, "\n/** The resource `{}`. */", c.path(i));
        let _ = writeln!(text, "export class {} {{", class_of(c, i));
        text.push_str("  readonly #core: $core.Core;\n");
        for &j in &children {
            let _ = writeln!(text, "  readonly {}: ${};", member_of(c, j), class_of(c, j));
        }
        text.push_str("\n  constructor(core: $core.Core) {\n    this.#core = core;\n");
        for &j in &children {
            let _ = writeln!(
                text,
                "    this.{} = new ${}(core);",
                member_of(c, j),
                class_of(c, j)
            );
        }
        text.push_str("  }\n");
        for (k, m) in c.methods.iter().enumerate() {
            if m.resource == i {
                method(ctx, k, m, &mut text, issues);
            }
        }
        text.push_str("}\n");
        out.push(super::file(&format!("src/{own}.ts"), text));
    }
    out
}

/// One method.
fn method(ctx: &Context<'_>, k: usize, m: &Method, out: &mut String, issues: &mut Issues) {
    let endpoint = ctx.endpoints.get(k).copied().flatten();
    let e = endpoint.and_then(|j| ctx.program.endpoints().get(j));
    let base = endpoint.and_then(|j| ctx.bases.get(j).cloned().flatten());
    let (Some(e), Some(base)) = (e, base) else {
        let message = format!(
            "`{}` has no functions in the SDK: the method is left out",
            m.op.name
        );
        issues.warn("client.method", &m.name.at, message);
        return;
    };
    let op = &e.operation;
    let name = camel(&words::words(&m.name.name));
    let summary = ctx
        .resolved
        .get(k)
        .copied()
        .flatten()
        .and_then(|i| ctx.ops.list.get(i))
        .and_then(|o| o.summary.as_deref())
        .map(|s| format!(": {}", doc(s)))
        .unwrap_or_default();
    let _ = writeln!(
        out,
        "\n  /** `{} {}`{summary} */",
        flowapi_ts::sdk_method(op),
        doc(&op.path)
    );
    let optional =
        !op.params.iter().any(|p| p.required) && !op.body.as_ref().is_some_and(|b| b.required);
    let params = format!(
        "params: $core.Input<typeof $api.{base}Request>{}, options?: $core.RequestOptions",
        if optional { " = {}" } else { "" }
    );
    let data = format!("$core.Data<typeof $api.{base}Response>");
    let table = format!("$api.flowapiOperations.{base}");
    let retries = m.retries.map(|r| format!(", {r}")).unwrap_or_default();
    let paging = effective(ctx.config, m).and_then(|n| find(ctx.config, &n.name));
    if m.stream.is_some() {
        let item = if sse_only(op) {
            "$core.ServerSentEvent"
        } else {
            "unknown"
        };
        let _ = writeln!(
            out,
            "  {name}({params}): $core.ApiCall<$core.Stream<{item}>> {{"
        );
        let _ = writeln!(
            out,
            "    return $core.stream(this.#core, {table}, params, options{retries});"
        );
    } else if let Some(p) = paging {
        let items = path(p.get("items").unwrap_or(""));
        let _ = writeln!(
            out,
            "  {name}({params}): $core.PagePromise<$core.ItemOf<{data}, {items}>> {{"
        );
        let _ = writeln!(
            out,
            "    return $core.page(this.#core, {table}, params, {}, options{retries});",
            scheme(p, op)
        );
    } else {
        let _ = writeln!(out, "  {name}({params}): $core.ApiCall<{data}> {{");
        let _ = writeln!(
            out,
            "    return $core.call(this.#core, {table}, params, options{retries});"
        );
    }
    out.push_str("  }\n");
}

/// Whether every streamed 2xx response is server-sent events.
fn sse_only(op: &Operation) -> bool {
    op.responses
        .iter()
        .filter(|r| r.status.starts_with('2'))
        .flat_map(|r| &r.content)
        .all(|m| {
            m.media_type
                .split(';')
                .next()
                .unwrap_or("")
                .trim()
                .eq_ignore_ascii_case("text/event-stream")
        })
}

/// A path in the body (`data.items`) as a tuple of members; `[]` for the body itself.
fn path(dotted: &str) -> String {
    if dotted.is_empty() {
        return String::from("[]");
    }
    let members: Vec<String> = dotted.split('.').map(lit).collect();
    format!("[{}]", members.join(", "))
}

/// Where a parameter of the operation goes, and its name.
fn place(op: &Operation, name: &str) -> String {
    let location = op
        .params
        .iter()
        .find(|p| p.name == name && p.location != Location::QueryString)
        .map_or("query", |p| p.location.name());
    format!("[{}, {}]", lit(location), lit(name))
}

/// A scheme as the runtime reads it (`Paging` in `core/pagination.ts`).
fn scheme(p: &Paging, op: &Operation) -> String {
    let mut fields = vec![format!("type: {}", lit(p.kind))];
    for (role, value) in &p.request {
        let key = if *role == "per_page" { "perPage" } else { role };
        fields.push(format!("{key}: {}", place(op, value)));
    }
    fields.push(format!("items: {}", path(p.get("items").unwrap_or(""))));
    for (role, value) in &p.response {
        match *role {
            "items" => {}
            "id" => fields.push(format!("id: {}", lit(value))),
            "header" => fields.push(format!("header: {}", lit(&value.to_ascii_lowercase()))),
            "has_more" => fields.push(format!("hasMore: {}", path(value))),
            "total_pages" => fields.push(format!("totalPages: {}", path(value))),
            other => fields.push(format!("{other}: {}", path(value))),
        }
    }
    match p.kind {
        "last_item_id" if p.get("id").is_none() => fields.push(String::from("id: \"id\"")),
        "page" => fields.push(format!("start: {}", p.start.unwrap_or(1))),
        "link" if p.get("next").is_none() && p.get("header").is_none() => {
            fields.push(String::from("header: \"link\""));
        }
        _ => {}
    }
    format!("{{ {} }}", fields.join(", "))
}
