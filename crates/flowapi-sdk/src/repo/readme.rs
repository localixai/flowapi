//! `README.md` and `api.md`, written from the config and the description, never by an agent:
//! the counts are the methods the client has (pitfall 16 of the study: a count typed by hand
//! drifts), the heading and first paragraph are the config's (`readme.title`, `readme.intro`,
//! `package.description`) or made from the description's `info`, the headline example is
//! `readme.headline_method` (else the first method) called with what its operation requires, and
//! a section is there only when the API has what it is about (environments, pagination,
//! streaming). The sections after the usage are in `readme/sections.rs`, `api.md` in
//! `readme/api.rs`, the authentication in `readme/auth.rs`; `tests/texts.mjs` compiles every example of both against the client.

mod api;
mod auth;
mod sections;
mod servers;

use super::suite::args;
use super::{Call, Ctx, HEADER, Kind, RepoFile, generated_file, package};
use crate::words;
use std::fmt::Write as _;

pub(crate) fn files(ctx: &Ctx<'_>) -> Vec<RepoFile> {
    vec![
        generated_file("README.md", readme(ctx)),
        generated_file("api.md", api::api(ctx)),
    ]
}

/// `n things`, `1 thing`.
fn plural(n: usize, one: &str) -> String {
    format!("{n} {one}{}", if n == 1 { "" } else { "s" })
}

/// `N methods in M resources`.
fn counted(ctx: &Ctx<'_>) -> String {
    let mut resources: Vec<usize> = ctx
        .calls
        .iter()
        .filter_map(|k| ctx.config.methods.get(k.method).map(|m| m.resource))
        .collect();
    resources.sort_unstable();
    resources.dedup();
    format!(
        "{} in {}",
        plural(ctx.calls.len(), "method"),
        plural(resources.len(), "resource")
    )
}

/// The method the README shows first: `readme.headline_method`, else the first.
fn headline<'c>(ctx: &'c Ctx<'_>) -> Option<&'c Call> {
    let wanted = ctx
        .config
        .readme
        .iter()
        .find(|(key, _)| *key == "headline_method")
        .map(|(_, n)| n.name.split('.').map(words::words).collect::<Vec<_>>());
    let same = |k: &&Call| {
        wanted
            .as_ref()
            .is_some_and(|w| k.name.split('.').map(words::words).eq(w.iter().cloned()))
    };
    ctx.calls.iter().find(same).or_else(|| ctx.calls.first())
}

/// What the README passes a method: the parameters and body its operation requires, as code;
/// nothing when it requires none.
fn input(ctx: &Ctx<'_>, call: &Call) -> String {
    ctx.ops
        .list
        .get(call.op)
        .and_then(|op| args(ctx, &op.operation, true))
        .map(|v| v.js())
        .unwrap_or_default()
}

fn readme(ctx: &Ctx<'_>) -> String {
    let package = ctx.package();
    let client = ctx.client();
    let s = &ctx.config.settings;
    let intro = s.intro.clone().unwrap_or_else(|| package::description(ctx));
    let mut out = format!(
        "<!-- {HEADER} -->\n\n# {}\n\n{intro}\n\nThe `{client}` client is generated by flowapi from the API's description: {}, each listed in [api.md](api.md) with its parameters and what it returns.\n\n",
        package::heading(ctx),
        counted(ctx)
    );
    let _ = writeln!(out, "## Install\n\n```sh\nnpm install {package}\n```\n");
    usage(ctx, &mut out);
    sections::resources(ctx, &mut out);
    auth::section(ctx, &mut out);
    sections::environments(ctx, &mut out);
    servers::servers(ctx, &mut out);
    let first = headline(ctx);
    sections::errors(ctx, first, &mut out);
    sections::retries(ctx, first, &mut out);
    sections::paging(ctx, &mut out);
    sections::logging(ctx, &mut out);
    sections::requests(&mut out);
    sections::closing(&mut out);
    out
}

/// The headline example, what a method takes and gives, and how the package is built.
fn usage(ctx: &Ctx<'_>, out: &mut String) {
    let package = ctx.package();
    let client = ctx.client();
    let _ = writeln!(
        out,
        "## Usage\n\n```ts\nimport {{ {client} }} from '{package}'\n\nconst client = new {client}()"
    );
    let call = headline(ctx);
    if let Some(call) = call {
        let _ = writeln!(
            out,
            "\nconst result = await client.{}({})",
            call.access,
            input(ctx, call)
        );
        if call.kind == Kind::Stream {
            out.push_str("for await (const event of result) console.log(event)\n");
        } else {
            out.push_str("console.log(result)\n");
        }
    }
    out.push_str("```\n\nA method takes its operation's parameters in one object, grouped by where each goes (`path`, `query`, `header`, `cookie`), with a body as `body: { contentType, value }`; it gives the response's body, read as the description says. A second argument changes one call (`headers`, `query`, `timeout`, `maxRetries`, `signal`). `withResponse()` gives the body with the raw response and the server's request id, `asResponse()` the raw response alone.\n");
    if let Some(call) = call {
        let _ = writeln!(
            out,
            "\n```ts\nconst {{ data, response, requestId }} = await client.{}({}).withResponse()\nconsole.log(response.status, requestId, data)\n```",
            call.access,
            input(ctx, call)
        );
    }
    let _ = writeln!(
        out,
        "\nThe package is built twice, as ES modules and as CommonJS, each with its types, and depends on nothing: it calls the platform's `fetch`. From CommonJS the client is taken by its name, `const {{ {client} }} = require('{package}')`; `import {client} from '{package}'` gives it too."
    );
}
