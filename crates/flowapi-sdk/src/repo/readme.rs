//! `README.md` and `api.md`, written from the config and the description, never by an agent:
//! the counts are the methods the client has (pitfall 16 of the study: a count typed by hand
//! drifts), the headline example is `readme.headline_method` (else the first method) called with
//! what its operation requires, and a section is there only when the API has what it is about
//! (environments, pagination, streaming). `api.md` lists every method by resource with the
//! types its TypeScript signature has.

use super::suite::{args, options};
use super::{Call, Ctx, HEADER, Kind, RepoFile, generated_file, package, texts};
use crate::client::camel;
use crate::config::check::{effective, find};
use crate::model::{Auth, KeyLocation};
use crate::words;
use std::fmt::Write as _;

pub(crate) fn files(ctx: &Ctx<'_>) -> Vec<RepoFile> {
    vec![
        generated_file("README.md", readme(ctx)),
        generated_file("api.md", api(ctx)),
    ]
}

/// `N methods in M resources`.
fn counted(ctx: &Ctx<'_>) -> String {
    let mut resources: Vec<usize> = ctx
        .calls
        .iter()
        .filter_map(|k| ctx.config.methods.get(k.method).map(|m| m.resource))
        .collect();
    resources.sort_unstable();
    resources.dedup();
    let plural = |n: usize, one: &str| format!("{n} {one}{}", if n == 1 { "" } else { "s" });
    format!(
        "{} in {}",
        plural(ctx.calls.len(), "method"),
        plural(resources.len(), "resource")
    )
}

/// The method the README shows first: `readme.headline_method`, else the first.
fn headline<'c>(ctx: &'c Ctx<'_>) -> Option<&'c Call> {
    let wanted = ctx
        .config
        .readme
        .iter()
        .find(|(key, _)| *key == "headline_method")
        .map(|(_, n)| n.name.split('.').map(words::words).collect::<Vec<_>>());
    let same = |k: &&Call| {
        wanted
            .as_ref()
            .is_some_and(|w| k.name.split('.').map(words::words).eq(w.iter().cloned()))
    };
    ctx.calls.iter().find(same).or_else(|| ctx.calls.first())
}

fn readme(ctx: &Ctx<'_>) -> String {
    let package = ctx.package();
    let client = ctx.client();
    let mut out = format!("<!-- {HEADER} -->\n\n# {package}\n\n");
    let intro = ctx.config.settings.intro.clone().unwrap_or_else(|| {
        let api =
            package::title(ctx).map_or_else(|| String::from("the API"), |t| format!("the {t} API"));
        format!("The TypeScript client of {api}, generated by flowapi from its description.")
    });
    let _ = writeln!(
        out,
        "{intro}\n\nIt has {}; [api.md](api.md) lists them.\n",
        counted(ctx)
    );
    let _ = writeln!(out, "## Install\n\n```sh\nnpm install {package}\n```\n");
    let _ = writeln!(
        out,
        "## Usage\n\n```ts\nimport {{ {client} }} from '{package}'\n\nconst client = new {client}()"
    );
    if let Some(call) = headline(ctx) {
        let input = ctx
            .ops
            .list
            .get(call.op)
            .and_then(|op| args(ctx, &op.operation, true));
        let input = input.map(|v| v.js()).unwrap_or_default();
        let _ = writeln!(
            out,
            "\nconst result = await client.{}({input})",
            call.access
        );
        if call.kind == Kind::Stream {
            out.push_str("for await (const event of result) console.log(event)\n");
        } else {
            out.push_str("console.log(result)\n");
        }
    }
    let _ = writeln!(
        out,
        "```\n\nThe package is ES modules and CommonJS both, with types for each, and has no dependency: it calls the platform's `fetch`. From CommonJS the client is taken by its name, `const {{ {client} }} = require('{package}')`; `import {client} from '{package}'` gives it too."
    );
    auth(ctx, &mut out);
    environments(ctx, &mut out);
    let s = &ctx.config.settings;
    let secs = |v: Option<f64>, d: f64| {
        let v = v.unwrap_or(d);
        if v.fract() == 0.0 {
            format!("{v:.0}")
        } else {
            format!("{v}")
        }
    };
    let _ = writeln!(
        out,
        "\n## Errors\n\nA status that is not a success throws an `APIError` with its `status`, `headers` and `body`, of the class for its status: `BadRequestError` (400), `AuthenticationError` (401), `PermissionDeniedError` (403), `NotFoundError` (404), `RequestTimeoutError` (408), `ConflictError` (409), `UnprocessableEntityError` (422), `RateLimitError` (429), `InternalServerError` (500 and above). No answer throws `APIConnectionError`; a timeout `APIConnectionTimeoutError`; a call aborted by its signal `APIUserAbortError`.\n\n```ts\nimport {{ APIError }} from '{package}'\n\ntry {{\n  await client.{}\n}} catch (error) {{\n  if (error instanceof APIError) console.log(error.status, error.body)\n  else throw error\n}}\n```",
        headline(ctx).map_or_else(
            || String::from("request('GET', '/')"),
            |c| format!("{}(/* … */)", c.access)
        )
    );
    let _ = writeln!(
        out,
        "\n## Retries and timeouts\n\nA call that fails to connect, or is answered 408, 409, 429 or 5xx, is tried {} more times by default, waiting longer each time (never more than {} s when the server asks to wait); each attempt may take {} s, its body read. Give `maxRetries` and `timeout` (milliseconds) to the client, or to one call:\n\n```ts\nconst client = new {client}({{ maxRetries: 0, timeout: 20_000 }})\n```",
        s.retries.unwrap_or(2),
        secs(s.max_retry_delay, 60.0),
        secs(s.timeout, 60.0),
    );
    paging(ctx, &mut out);
    let _ = writeln!(
        out,
        "\n## Requirements\n\nNode {} or later (CI runs {}), or any runtime with `fetch`. Built with TypeScript {}.\n\n## Development\n\n```sh\nnpm install\nscripts/check   # lint, build, the built types, the tests against the mock server\n```\n\nThe code is generated from `flowapi-sdk.yml`: change that file and generate again ([AGENTS.md](AGENTS.md)).",
        texts::NODES.first().copied().unwrap_or("20"),
        texts::NODES.join(", "),
        package::TYPESCRIPT
    );
    out
}

fn auth(ctx: &Ctx<'_>, out: &mut String) {
    if ctx.config.auth.is_empty() {
        return;
    }
    out.push_str("\n## Authentication\n\nEach credential is an option of the client, else read from its environment variable:\n\n| Scheme | Sent as | Option | Variable |\n| --- | --- | --- | --- |\n");
    for a in &ctx.config.auth {
        let sent = ctx
            .service
            .schemes
            .iter()
            .find(|s| s.name == a.name)
            .map_or_else(String::new, |s| match &s.auth {
                Auth::ApiKey { location, name } => format!(
                    "an API key in the {} `{name}`",
                    match location {
                        KeyLocation::Header => "header",
                        KeyLocation::Query => "query parameter",
                        KeyLocation::Cookie => "cookie",
                    }
                ),
                Auth::Http { scheme, .. } if scheme == "basic" => {
                    String::from("HTTP basic (`{ username, password }`)")
                }
                Auth::Http { scheme, .. } => format!("HTTP `{scheme}`"),
                Auth::OAuth2 { .. } => String::from("an OAuth 2.0 token"),
                Auth::OpenIdConnect { .. } => String::from("an OpenID Connect token"),
                Auth::MutualTls => String::from("a client certificate"),
            });
        let var = ctx
            .config
            .settings
            .auth_env
            .iter()
            .find(|(n, _)| *n == a.name)
            .map_or_else(|| String::from("—"), |(_, v)| format!("`{v}`"));
        let _ = writeln!(
            out,
            "| `{}` | {sent} | `{}` | {var} |",
            a.name,
            camel(&words::words(&a.name))
        );
    }
    let _ = writeln!(
        out,
        "\n```ts\nconst client = new {}({})\n```",
        ctx.client(),
        options(ctx, None)
    );
}

fn environments(ctx: &Ctx<'_>, out: &mut String) {
    let s = &ctx.config.settings;
    if s.urls.is_empty() {
        return;
    }
    out.push_str("\n## Environments\n\n| Environment | Base URL |\n| --- | --- |\n");
    for (name, url) in &s.urls {
        let _ = writeln!(out, "| `{name}` | {url} |");
    }
    let default = ctx
        .config
        .default_environment
        .as_ref()
        .map(|n| n.name.as_str());
    let first = s.urls.first().map(|(n, _)| n.as_str());
    let _ = write!(
        out,
        "\nThe client calls `{}` unless given `environment` or `baseURL`",
        default.or(first).unwrap_or("")
    );
    match &s.base_url_env {
        Some(var) => {
            let _ = writeln!(out, ", or `{var}` is set.");
        }
        None => out.push_str(".\n"),
    }
}

fn paging(ctx: &Ctx<'_>, out: &mut String) {
    let c = ctx.config;
    let named = |key: &str| {
        c.readme
            .iter()
            .find(|(k, _)| *k == key)
            .map(|(_, n)| n.name.clone())
    };
    let page = ctx
        .calls
        .iter()
        .find(|k| named("pagination_method").is_some_and(|n| n == k.name))
        .or_else(|| ctx.calls.iter().find(|k| k.kind == Kind::Page));
    if let Some(call) = page {
        let _ = writeln!(
            out,
            "\n## Pagination\n\nA list is read a page at a time; `for await` reads every item, asking for the next page as it needs one:\n\n```ts\nfor await (const item of client.{}()) console.log(item)\n\nconst page = await client.{}()\nconsole.log(page.items)\n```",
            call.access, call.access
        );
    }
    if let Some(call) = ctx.calls.iter().find(|k| k.kind == Kind::Stream) {
        let _ = writeln!(
            out,
            "\n## Streaming\n\nA streamed method gives its events as they come:\n\n```ts\nfor await (const event of await client.{}()) console.log(event)\n```",
            call.access
        );
    }
}

fn api(ctx: &Ctx<'_>) -> String {
    let c = ctx.config;
    let mut out = format!(
        "<!-- {HEADER} -->\n\n# API\n\n{} of `{}`.\n",
        counted(ctx),
        ctx.client()
    );
    for (i, _) in c.resources.iter().enumerate() {
        let calls: Vec<&Call> = ctx
            .calls
            .iter()
            .filter(|k| c.methods.get(k.method).is_some_and(|m| m.resource == i))
            .collect();
        if calls.is_empty() {
            continue;
        }
        let _ = writeln!(out, "\n## {}\n", c.path(i));
        for call in calls {
            let Some(op) = ctx.ops.list.get(call.op) else {
                continue;
            };
            let o = &op.operation;
            let optional = !o.params.iter().any(|p| p.required)
                && !o.body.as_ref().is_some_and(|b| b.required);
            let data = format!("Data<typeof {}Response>", call.base);
            let returns = match call.kind {
                Kind::Call => format!("ApiCall<{data}>"),
                Kind::Stream => String::from("ApiCall<Stream<…>>"),
                Kind::Page => {
                    let items = c
                        .methods
                        .get(call.method)
                        .and_then(|m| effective(c, m))
                        .and_then(|n| find(c, &n.name))
                        .and_then(|p| p.get("items"))
                        .unwrap_or("");
                    let tuple: Vec<String> = items
                        .split('.')
                        .filter(|m| !m.is_empty())
                        .map(|m| format!("\"{m}\""))
                        .collect();
                    format!("PagePromise<ItemOf<{data}, [{}]>>", tuple.join(", "))
                }
            };
            let summary = op
                .summary
                .as_deref()
                .map(|s| format!(": {}", s.split_whitespace().collect::<Vec<_>>().join(" ")))
                .unwrap_or_default();
            let _ = writeln!(
                out,
                "- `client.{}(params{}: Input<typeof {}Request>, options?: RequestOptions): {returns}`  \n  `{} {}`{summary}",
                call.access,
                if optional { "?" } else { "" },
                call.base,
                op.method(),
                o.path
            );
        }
    }
    out
}
