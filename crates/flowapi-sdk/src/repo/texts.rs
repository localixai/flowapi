//! The files that are the same for every API but the package's version: the POSIX scripts
//! (`files/scripts/`), CI on Node 20, 22 and 24 running `scripts/check`, the release tool's
//! config (release-please, which raises `package.version` in `flowapi-sdk.yml` beside
//! `package.json`, so that the next generation prints what it released), `.gitignore`, and
//! `examples/.keep`. On the first generation also the files the release tool keeps afterwards,
//! `CHANGELOG.md` and `.release-please-manifest.json`, which are never generated again.

use super::{Ctx, HEADER, Owner, RepoFile, generated_file};
use crate::out::json_str;

/// The scripts, by name: `scripts/check` is what CI and the judge run.
const SCRIPTS: &[(&str, &str)] = &[
    ("build", include_str!("files/scripts/build")),
    ("check", include_str!("files/scripts/check")),
    ("lint", include_str!("files/scripts/lint")),
    ("mock", include_str!("files/scripts/mock")),
    ("test", include_str!("files/scripts/test")),
];

/// The Node versions CI runs on: the README says the oldest.
pub(crate) const NODES: &[&str] = &["20", "22", "24"];

const RELEASE: &str = r#"{
  "$schema": "https://raw.githubusercontent.com/googleapis/release-please/main/schemas/config.json",
  "packages": {
    ".": {
      "release-type": "node",
      "include-v-in-tag": true,
      "bump-minor-pre-major": true,
      "changelog-path": "CHANGELOG.md",
      "extra-files": [{ "type": "yaml", "path": "flowapi-sdk.yml", "jsonpath": "$.package.version" }]
    }
  }
}
"#;

pub(crate) fn files(ctx: &Ctx<'_>, first: bool) -> Vec<RepoFile> {
    let mut out: Vec<RepoFile> = SCRIPTS
        .iter()
        .map(|(name, text)| generated_file(&format!("scripts/{name}"), (*text).to_owned()))
        .collect();
    out.push(generated_file(".github/workflows/ci.yml", ci()));
    out.push(generated_file(
        "release-please-config.json",
        RELEASE.to_owned(),
    ));
    out.push(generated_file(
        ".gitignore",
        format!("# {HEADER}\nnode_modules/\ndist/\n*.tgz\n"),
    ));
    out.push(generated_file("examples/.keep", String::new()));
    out.push(generated_file("AGENTS.md", agents()));
    if first {
        out.push(seed(
            "CHANGELOG.md",
            format!(
                "# Changelog\n\nEach release of `{}`, newest first. release-please writes an entry from the commits since the release before it.\n",
                ctx.package()
            ),
        ));
        out.push(seed(
            ".release-please-manifest.json",
            format!("{{\n  \".\": {}\n}}\n", json_str(ctx.version())),
        ));
    }
    out
}

fn seed(path: &str, text: String) -> RepoFile {
    RepoFile {
        path: path.to_owned(),
        text,
        executable: false,
        owner: Owner::Seed,
    }
}

fn ci() -> String {
    format!(
        "# {HEADER}\n\nname: CI\n\non:\n  push:\n    branches: [main]\n  pull_request:\n\npermissions:\n  contents: read\n\njobs:\n  check:\n    runs-on: ubuntu-latest\n    strategy:\n      matrix:\n        node: [{}]\n    steps:\n      - uses: actions/checkout@v4\n      - uses: actions/setup-node@v4\n        with:\n          node-version: ${{{{ matrix.node }}}}\n      - run: npm install --no-audit --no-fund\n      - run: scripts/check\n",
        NODES.join(", ")
    )
}

/// The guide of the SDK's repository, for the agent or the person who keeps it.
fn agents() -> String {
    format!(
        "<!-- {HEADER} -->\n\n# AGENTS.md\n\n\
This repository is a TypeScript SDK generated by flowapi from `flowapi-sdk.yml` and the API \
description its `spec` names.\n\n\
## Where things are\n\n\
- `src/client.ts`: the client class and its options; `src/resources/`: a class per resource, a \
method per operation; `src/api.ts`: the types and each operation's request and response; \
`src/core/`: the runtime (sending, retries, errors, pagination, streams).\n\
- `mock/`: the mock server the tests run against; `tests/api-resources/`: a test per resource.\n\
- `README.md` and `api.md`: the package's documentation, every method in `api.md`.\n\n\
## What is generated\n\n\
Every file listed under `files` in `.flowapi/lock.json`, with the hash of what was written. \
Do not edit one: change `flowapi-sdk.yml` (or the description) and generate again:\n\n\
```sh\nnpx -y @localix-ai/flowapi@{version} config check flowapi-sdk.yml   # every issue at once\n\
npx -y @localix-ai/flowapi@{version} generate flowapi-sdk.yml --out .\n```\n\n\
A generated file changed by hand is a conflict: generate names it, stops and writes nothing. \
A file generated before and no longer generated is deleted, unless it was changed.\n\n\
## Changing the SDK\n\n\
| To change | Edit in `flowapi-sdk.yml` |\n| --- | --- |\n\
| A method's name, or which resource it is in | `resources.<resource>.methods` |\n\
| An operation left out, with why | `skip` |\n\
| The base URLs | `environments` |\n\
| Retries, the timeout, the default pagination | `defaults` |\n\
| How a list pages | `pagination`, and a method's `pagination` |\n\
| The README's heading, first paragraph and examples | `readme.title`, `readme.intro`, \
`readme.headline_method`, `readme.pagination_method` |\n\
| `package.json`'s description and keywords | `package.description`, `package.keywords` |\n\n\
## What is yours\n\n\
- `src/lib/` and `examples/`: generate writes a file there only while it is unchanged, and \
never overwrites one you changed.\n\
- `CHANGELOG.md` and `.release-please-manifest.json`: written on the first generation, then the \
release tool's.\n\
- Every file the lock does not list: generate never touches it.\n\n\
## Commands\n\n\
```sh\nnpm install       # TypeScript, the one development dependency\n\
scripts/check     # everything: lint, build, the built types, the tests\n\
scripts/build     # dist/esm and dist/cjs, then both loaded by the package's name\n\
scripts/lint      # the types, no node: module in the client, the tests parsed\n\
scripts/test      # node --test over tests/, against the mock server each file starts\n\
scripts/mock      # the mock server on port 4010, for trying the client by hand\n```\n\n\
The mock (`mock/routes.mjs`) answers each operation with an example of its schema and refuses \
a request its operation would refuse: a wrong path or method, a missing parameter, a body of \
another media type. Set `TEST_API_BASE_URL` to run the tests against another server.\n\n\
## Releases\n\n\
release-please opens the release pull request: it raises `package.version` in \
`flowapi-sdk.yml` and `package.json` together, so the next generation prints the version \
released, and writes the release's entry in `CHANGELOG.md`. Publishing is a person's step.\n",
        version = env!("CARGO_PKG_VERSION"),
    )
}
