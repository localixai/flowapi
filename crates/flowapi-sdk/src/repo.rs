use std::collections::BTreeMap;

/// Where the lock is, from the repository's root.
pub const LOCK_PATH: &str = ".flowapi/lock.json";

/// The folders whose files are the user's own: the generator writes a file there once and never
/// overwrites one that was changed (the plugin's guard lets an agent edit them).
pub const OWN_ZONES: &[&str] = &["src/lib/", "examples/"];

/// The comment every generated text file opens with, where its format has comments.
pub(crate) const HEADER: &str = "Generated by flowapi from flowapi-sdk.yml and the API description. Do not edit: generate again.";

/// Whether a path is under one of [`OWN_ZONES`].
#[must_use]
pub fn is_own(path: &str) -> bool {
    OWN_ZONES.iter().any(|z| path.starts_with(z))
}

/// What a repository is generated from: the config as JSON (the host reads YAML into JSON), and
/// the bytes of the config and the description as read, which the lock holds the hashes of.
#[derive(Clone, Copy, Debug)]
pub struct Input<'a> {
    /// The config's JSON text.
    pub config: &'a str,
    /// The config file's bytes.
    pub config_bytes: &'a [u8],
    /// The description file's bytes (the first document).
    pub spec_bytes: &'a [u8],
}

/// Who a file belongs to once written.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Owner {
    /// The generator: listed in the lock, rewritten by every generation.
    Generated,
    /// The user or the release tool: written only on the first generation, when it is absent,
    /// and never listed in the lock (`CHANGELOG.md`, `.release-please-manifest.json`).
    Seed,
}

/// A file of the repository.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct RepoFile {
    /// From the repository's root, with `/`.
    pub path: String,
    /// Its text.
    pub text: String,
    /// Whether it is run as a program (`scripts/*`).
    pub executable: bool,
    /// Who it belongs to.
    pub owner: Owner,
}

/// What [`repo_files`] made.
#[derive(Debug, Default)]
pub struct Repo {
    /// Every file but the lock, sorted by path; none when an issue is an error.
    pub files: Vec<RepoFile>,
    /// The lock of these files, written to [`LOCK_PATH`].
    pub lock: Lock,
    /// What reading the description found.
    pub diagnostics: Diagnostics,
    /// What holding the config to the description and printing the files found.
    pub issues: Vec<Issue>,
}

/// How a method is called.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum Kind {
    Call,
    Page,
    Stream,
}

/// A method the client has.
pub(crate) struct Call {
    /// Its index in the config's methods.
    pub(crate) method: usize,
    /// Its name from the client, as the config writes it: `pets.photos.list`.
    pub(crate) name: String,
    /// The members a caller writes after the client: `pets.photos.list`.
    pub(crate) access: String,
    /// Its operation, by index into the description's operations.
    pub(crate) op: usize,
    /// The TypeScript SDK's name for its functions (`listPets` of `listPetsRequest`).
    pub(crate) base: String,
    pub(crate) kind: Kind,
}

/// What the files around the client are printed from.
pub(crate) struct Ctx<'a> {
    pub(crate) config: &'a Config,
    pub(crate) ops: &'a Ops<'a, 'a>,
    pub(crate) service: &'a Service,
    pub(crate) calls: Vec<Call>,
}

impl Ctx<'_> {
    /// The package's name.
    pub(crate) fn package(&self) -> &str {
        self.config.settings.package.as_deref().unwrap_or("sdk")
    }

    /// The client class's name.
    pub(crate) fn client(&self) -> String {
        let client = self
            .config
            .client
            .as_ref()
            .map_or("Client", |n| n.name.as_str());
        words::pascal(&words::words(client))
    }

    /// The package's version.
    pub(crate) fn version(&self) -> &str {
        self.config.settings.version.as_deref().unwrap_or("0.1.0")
    }
}

/// The repository of an SDK: its files sorted by path, and their lock. `previous` is the lock of
/// the last generation, when there was one: the files the user or the release tool keeps
/// (`CHANGELOG.md`) are printed only without it. Nothing is printed when an issue is an error.
#[must_use]
pub fn repo_files(
    docs: &Documents<'_>,
    program: &Program<'_>,
    input: &Input<'_>,
    previous: Option<&Lock>,
) -> Repo {
    let mut check = checked(docs, input.config);
    let issues = std::mem::take(&mut check.issues);
    let generated = client::print(docs, program, issues, &check);
    let mut repo = Repo {
        diagnostics: generated.diagnostics,
        issues: generated.issues,
        ..Repo::default()
    };
    let (Some(ops), false) = (
        Ops::read(docs).0,
        repo.issues.iter().any(|i| i.severity == Severity::Error),
    ) else {
        return repo;
    };
    let (service, _) = crate::read(docs, program);
    let ctx = Ctx {
        config: &check.config,
        ops: &ops,
        service: &service,
        calls: calls(&check.config, program, &ops, &check.resolved),
    };
    let mut files: Vec<RepoFile> = generated
        .files
        .into_iter()
        .map(|f| generated_file(&f.path, f.text))
        .collect();
    let mut found = Issues::default();
    files.extend(package::files(&ctx, &mut found));
    repo.issues.extend(found.list);
    files.extend(texts::files(&ctx, previous.is_none()));
    files.extend(readme::files(&ctx));
    files.extend(mock::files(&ctx));
    files.extend(suite::files(&ctx));
    if repo.issues.iter().any(|i| i.severity == Severity::Error) {
        return repo;
    }
    files.sort_by(|a, b| a.path.cmp(&b.path));
    repo.lock = Lock {
        version: 1,
        flowapi: env!("CARGO_PKG_VERSION").to_owned(),
        spec_sha256: sha256_hex(input.spec_bytes),
        config_sha256: sha256_hex(input.config_bytes),
        configured_endpoints: ctx.calls.len(),
        files: files
            .iter()
            .filter(|f| f.owner == Owner::Generated)
            .map(|f| (f.path.clone(), sha256_hex(f.text.as_bytes())))
            .collect(),
        names: BTreeMap::new(),
    };
    repo.files = files;
    repo
}

/// A file the generator owns.
pub(crate) fn generated_file(path: &str, text: String) -> RepoFile {
    RepoFile {
        path: path.to_owned(),
        executable: path.starts_with("scripts/"),
        text,
        owner: Owner::Generated,
    }
}

/// Every method the client prints, in the config's order: one whose operation has no functions
/// in the SDK was left out with a warning by the client, and is left out here.
fn calls(
    c: &Config,
    program: &Program<'_>,
    ops: &Ops<'_, '_>,
    resolved: &[Option<usize>],
) -> Vec<Call> {
    let bases = flowapi_ts::sdk_bases(program);
    let endpoints: BTreeMap<String, usize> = program
        .endpoints()
        .iter()
        .enumerate()
        .map(|(i, e)| (client::route(&e.operation), i))
        .collect();
    let mut out = Vec::new();
    for (k, m) in c.methods.iter().enumerate() {
        let Some(op) = resolved.get(k).copied().flatten() else {
            continue;
        };
        let Some(o) = ops.list.get(op) else { continue };
        let base = endpoints
            .get(&client::route(&o.operation))
            .and_then(|&i| bases.get(i).cloned().flatten());
        let Some(base) = base else { continue };
        let mut members = Vec::new();
        let mut next = Some(m.resource);
        while let Some(r) = next {
            members.push(resources::member_of(c, r));
            next = c.resources.get(r).and_then(|x| x.parent);
            if members.len() > c.resources.len() {
                break;
            }
        }
        members.reverse();
        members.push(client::camel(&words::words(&m.name.name)));
        let kind = if m.stream.is_some() {
            Kind::Stream
        } else if effective(c, m).and_then(|n| find(c, &n.name)).is_some() {
            Kind::Page
        } else {
            Kind::Call
        };
        out.push(Call {
            method: k,
            name: format!("{}.{}", c.path(m.resource), m.name.name),
            access: members.join("."),
            op,
            base,
            kind,
        });
    }
    out
}
