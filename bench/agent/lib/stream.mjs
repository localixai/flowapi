// What one `claude -p --output-format stream-json --verbose` run says of itself, read from its
// events, one JSON object a line: the model the `system/init` event names, every tool call with
// its result, the final `result` (turns, cost, time, its text), the config issue codes the agent
// was shown, and the guard's refusals. A line that is not JSON is counted, never thrown on: a
// run cut short still has its first events read.

/** The text of a tool result's `content`: a string, or a list of text blocks. */
function text(content) {
  if (typeof content === 'string') return content
  if (!Array.isArray(content)) return ''
  return content.map((block) => (typeof block?.text === 'string' ? block.text : '')).join('\n')
}

// An issue code as `config check` prints it: `warning[config.auth.none]` in text, or
// `"code":"config.auth.none"` in its --json.
const CODE = /(?:(?:warning|error)\[|"code"\s*:\s*")(config\.[a-z_.]+)/g

// The guard hook's denial: every reason it gives names the lock (plugins/flowapi/lib/guard.mjs).
const REFUSAL = /written by flowapi generate alone|is generated by flowapi from flowapi-sdk\.yml/

/** Reads the events of one run. */
export function parseStream(input) {
  const run = {
    model: null,
    sessionId: null,
    plugins: [],
    turns: null,
    costUsd: null,
    durationMs: null,
    isError: null,
    subtype: null,
    result: '',
    toolUses: [],
    seenCodes: [],
    refusals: [],
    badLines: 0,
  }
  const uses = new Map()
  const seen = new Set()
  for (const line of input.split('\n')) {
    if (line.trim() === '') continue
    let event
    try {
      event = JSON.parse(line)
    } catch {
      run.badLines++
      continue
    }
    if (event.type === 'system' && event.subtype === 'init') {
      run.model = event.model ?? null
      run.sessionId = event.session_id ?? null
      run.plugins = (event.plugins ?? []).map((p) => p?.name ?? String(p))
    } else if (event.type === 'assistant') {
      for (const block of event.message?.content ?? []) {
        if (block.type !== 'tool_use') continue
        const use = { id: block.id, name: block.name, input: block.input ?? {}, isError: null }
        uses.set(block.id, use)
        run.toolUses.push(use)
      }
    } else if (event.type === 'user') {
      const content = event.message?.content
      for (const block of Array.isArray(content) ? content : []) {
        if (block.type !== 'tool_result') continue
        const said = text(block.content)
        const use = uses.get(block.tool_use_id)
        if (use) use.isError = block.is_error === true
        for (const match of said.matchAll(CODE)) seen.add(match[1])
        if (REFUSAL.test(said)) run.refusals.push({ tool: use?.name ?? null, path: use?.input?.file_path ?? null })
      }
    } else if (event.type === 'result') {
      run.turns = event.num_turns ?? null
      run.costUsd = event.total_cost_usd ?? null
      run.durationMs = event.duration_ms ?? null
      run.isError = event.is_error ?? null
      run.subtype = event.subtype ?? null
      run.result = typeof event.result === 'string' ? event.result : ''
    }
  }
  run.seenCodes = [...seen].sort()
  return run
}
